"""Base interfaces and typed schemas for FLARE LLM Provider Abstraction (M10.5)."""
from __future__ import annotations

from abc import ABC, abstractmethod
from enum import Enum
from typing import Any
from pydantic import BaseModel, Field


class LLMProviderStatus(str, Enum):
    """Health/availability status of an LLM provider."""
    AVAILABLE = "available"
    UNAVAILABLE = "unavailable"
    DEGRADED = "degraded"


class ProviderUnavailableError(Exception):
    """Raised when an LLM provider is unreachable, times out, or fails fatally."""
    def __init__(self, message: str, provider: str = "unknown", original_error: Exception | None = None) -> None:
        super().__init__(message)
        self.provider = provider
        self.original_error = original_error


class LLMMessage(BaseModel):
    """Standard conversational or instructional message."""
    role: str = Field(..., description="Role: system, user, assistant")
    content: str = Field(..., description="Message text content")


class LLMResponse(BaseModel):
    """Standardized response produced by any LLM provider."""
    content: str = Field(..., description="Raw text response generated by the model")
    model: str = Field(..., description="Model identifier used for generation")
    provider: str = Field(..., description="Provider name e.g. ollama, mock")
    duration_seconds: float = Field(default=0.0, description="Inference latency in seconds")
    raw_metadata: dict[str, Any] = Field(default_factory=dict, description="Provider-specific token counts or stats")


class BaseLLMProvider(ABC):
    """Abstract interface governing all LLM synthesis providers in FLARE."""

    @property
    @abstractmethod
    def provider_name(self) -> str:
        """Name of the provider implementation."""
        pass

    @property
    @abstractmethod
    def model_name(self) -> str:
        """Target model identifier."""
        pass

    @abstractmethod
    def generate_sync(
        self,
        prompt: str,
        system_prompt: str | None = None,
        response_format: str | None = None,
        temperature: float = 0.1,
    ) -> LLMResponse:
        """Synchronously generate text or JSON output from the provider.
        
        Raises:
            ProviderUnavailableError: If provider cannot be reached or fails.
        """
        pass

    @abstractmethod
    def is_available(self) -> bool:
        """Check if the provider endpoint and model are ready and responding."""
        pass
